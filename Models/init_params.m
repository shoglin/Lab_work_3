%% Расчет номиналов для SimScape
% Этот скрипт автоматически подгружает переменные в Workspace

i = 18;
U1 = 3.3;

% 1. Сопротивления (Ом)
if i < 10
    R1 = i * 1750;
    R2 = i * 175;
else
    R1 = i * 875;
    R2 = i * 85;
end

% 2. Емкости (Фарады)
if i < 10
    C1 = (mod(i, 3) + 1) * 1e-6;
    C2 = (mod(i, 2) + 1) * 1e-6;
else
    C1 = (mod(i, 2) + 1) * 1e-6;
    C2 = (mod(i, 2) + 2) * 1e-6;
end

% 3. Индуктивность (Генри)
if i < 10
    L = (mod(i, 3) + 1) * 2;
else
    L = (mod(i, 2) + 1) * 2;
end

%% Вывод в консоль для проверки
fprintf('--- Параметры SimScape обновлены (i = %d) ---\n', i);
fprintf('R1 = %.1f Ом, R2 = %.1f Ом\n', R1, R2);
fprintf('C1 = %.1e Ф, C2 = %.1e Ф\n', C1, C2);
fprintf('L  = %.1f Гн, U1 = %.1f В\n', L, U1);